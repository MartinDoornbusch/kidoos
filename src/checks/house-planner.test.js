"use strict";
const assert=require("node:assert/strict");
const D=require("../house-designer.js");
const H=require("../house-planner.js");
const C=require("../construction-campaign.js");
const B=require("../construction-projects.js");
let design=D.create({projectId:"huis-1",plotId:"kavel-1",x:10,z:20});
assert.equal(D.valid(design).valid,true);
assert.equal(D.visualPlan(design,0).visible.length,0);
assert.equal(D.visualPlan(design,1).visible.length,1);
assert.equal(D.visualPlan(design,5).visible.length,16);
const original=JSON.parse(JSON.stringify(design));
const rotated=D.edit(design,{rotation:90,roof:"hip",roofMaterial:"slate"});
assert.equal(design.rotation,0,"edit must not mutate source");
assert.equal(rotated.rotation,90);
assert.deepEqual(design,original);
assert.equal(D.checkSite(design,{plot:{id:"kavel-1",x:10,z:20,width:12,depth:8}}).ok,false,"world check required");
const location={plot:{id:"kavel-1",x:10,z:20,width:12,depth:8},worldCheck:()=>true};
assert.equal(D.checkSite(design,location).ok,true);
assert.equal(D.checkSite(rotated,location).ok,false,"90 degree rotation should fail narrow lot");
const obstacle={...location,obstacles:[{id:"tree",x:14,z:20,radius:1}]};
assert.equal(D.checkSite(design,obstacle).ok,false,"tree should block lot");
assert.equal(D.checkSite(design,{...location,worldCheck:()=>({valid:false,reason:"path-obstructed"})}).ok,false);
assert.throws(()=>D.edit(design,{rotation:90},1),/foundation-locked/);
assert.throws(()=>D.edit(design,{facade:"stone"},3),/walls-locked/);
assert.throws(()=>D.edit(design,{roof:"hip"},4),/roof-locked/);
design=D.door(design,"back");
assert.equal(design.door.side,"back");
assert.throws(()=>D.addWindow(design,"back","center"),/window-at-door/);
design=D.addWindow(design,"left","center");
assert.equal(design.windows.length,5);
design=D.removeWindow(design,"left","center");
assert.equal(design.windows.length,4);
let save={hout:20,steen:20,planken:20,munten:9,builds:[{x:1,z:2,type:"blok"}],constructionProjects:[]};
const before=JSON.parse(JSON.stringify(save));
const notApproved=H.begin(save,design,{plot:location.plot});
assert.equal(notApproved.ok,false);
let begun=H.begin(save,design,location);
assert.equal(begun.ok,true);
assert.deepEqual(save,before,"begin must be immutable");
assert.strictEqual(begun.save.builds,save.builds);
assert.equal(begun.save.constructionProjects[0].blueprintId,"vakwerkhuis");
assert.equal(H.begin(begun.save,design,location).ok,false,"duplicated house");
let editing=H.change(begun.save,"huis-1",{roof:"hip"});
assert.equal(editing.ok,true);
assert.equal(editing.save.constructionDesigns["huis-1"].roof,"hip");
assert.equal(H.change(editing.save,"huis-1",{rotation:90},location).ok,false,"bad plot after rotation");
const complete={...editing.save,constructionProjects:editing.save.constructionProjects.map(p=>({...p,completed:5}))};
const noInventory=H.placeFurniture({...complete,hout:0,planken:0},"huis-1",{id:"bed-1",type:"bed",x:-2,z:0,rotation:0});
assert.equal(noInventory.reason,"needs-materials");
let furnished=H.placeFurniture(complete,"huis-1",{id:"bed-1",type:"bed",x:-2,z:0,rotation:0});
assert.equal(furnished.ok,true);
assert.equal(furnished.save.hout,19);
assert.equal(furnished.save.planken,17);
assert.equal(H.placeFurniture(furnished.save,"huis-1",{id:"chair-1",type:"chair",x:-2,z:0,rotation:0}).ok,false,"overlap");
const moved=H.moveFurniture(furnished.save,"huis-1","bed-1",{x:-2,z:-1});
assert.equal(moved.ok,true);
const stored=H.storeFurniture(moved.save,"huis-1","bed-1");
assert.equal(stored.ok,true);
assert.equal(stored.save.houseFurnitureStorage.length,1);
const reused=H.placeFurniture(stored.save,"huis-1",{id:"bed-1",type:"bed",x:-2,z:0,rotation:0});
assert.equal(reused.ok,true);
assert.equal(reused.reused,true);
assert.equal(reused.save.hout,19);
assert.equal(reused.save.planken,17);
assert.equal(reused.save.houseFurnitureStorage.length,0);
const restored=JSON.parse(JSON.stringify(reused.save));
assert.equal(H.get(restored,"huis-1").ok,true,"save/load design");
assert.equal(B.progress(restored.constructionProjects[0]).finished,true);
assert.equal(C.state(restored,"huis-1").progress.finished,true);
console.log("house-designer + house-planner: tests geslaagd");
