"use strict";
const assert = require("node:assert/strict");
const P = require("../construction-projects.js");
const C = require("../construction-campaign.js");
const S = require("../construction-story.js");
const original = {hout:20,steen:20,planken:20,munten:3,builds:[{x:1,y:0,z:2,type:"blok"}],otherSetting:{value:8}};
const a = C.start(original,{id:"tower-one",plotId:"site-tower",blueprintId:"wachttoren_ruine",x:22,z:-11});
assert.equal(a.ok,true);
assert.equal(original.constructionProjects,undefined);
assert.strictEqual(a.save.builds,original.builds,"existing free buildings remain untouched");
assert.equal(a.save.constructionProjects.length,1);
assert.equal(C.start(a.save,{id:"tower-one",plotId:"other",blueprintId:"vakwerkhuis",x:0,z:0}).reason,"project-exists");
assert.equal(C.start(a.save,{id:"house",plotId:"site-tower",blueprintId:"vakwerkhuis",x:0,z:0}).reason,"plot-occupied");
const b=C.start(a.save,{id:"house",plotId:"home-1",blueprintId:"vakwerkhuis",x:5,z:5});
assert.equal(b.ok,true);
let save=b.save;
assert.equal(C.summary(save).length,2);
assert.deepEqual(P.budget("wachttoren_ruine"),{hout:7,steen:9,planken:9,questions:7});
assert.deepEqual(P.budget("vakwerkhuis"),{hout:10,steen:9,planken:9,questions:6});
assert.equal(S.get("wachttoren_ruine").steps.length,5);
for(const id of ["wachttoren_ruine","vakwerkhuis"])assert.deepEqual(S.get(id).steps.map(x=>x.id),P.blueprint(id).stages.map(x=>x.id));
let demo=C.state(save,"tower-one");
assert.equal(demo.progress.next.id,"survey");
assert.equal(C.complete(save,"tower-one").reason,"needs-answers");
const wrong={eventId:"quiz-attempt-1",questionId:"Q1",subject:"Nederlands",stageId:"survey",correct:false,verified:true};
assert.equal(C.answer(save,"tower-one",wrong).reason,"unverified-answer");
assert.equal(C.answer(save,"tower-one",{...wrong,correct:true,verified:false}).reason,"unverified-answer");
assert.equal(C.answer(save,"tower-one",{...wrong,correct:true,stageId:"clear"}).reason,"unverified-answer");
let accepted=C.answer(save,"tower-one",{...wrong,correct:true});
assert.equal(accepted.ok,true);
assert.equal(C.answer(accepted.save,"tower-one",{...wrong,correct:true}).reason,"duplicate-answer");
assert.equal(C.answer(accepted.save,"tower-one",{...wrong,correct:true,eventId:"quiz-attempt-2"}).reason,"duplicate-answer");
assert.equal(save.constructionStudy["tower-one"],undefined);
save=accepted.save;
assert.equal(C.state(save,"tower-one").canFinishStep,true);
let done=C.complete(save,"tower-one");
assert.equal(done.ok,true);
assert.equal(done.stage,"survey");
assert.equal(done.save.constructionStudy["tower-one"],undefined);
assert.equal(done.save.constructionProjects.find(x=>x.id==="tower-one").completed,1);
assert.equal(save.constructionProjects.find(x=>x.id==="tower-one").completed,0,"no in-place mutation");
assert.equal(done.rewards,null);
save=done.save;
let attemptNo=0;
while(!C.state(save,"tower-one").progress.finished){
  const stage=C.state(save,"tower-one").progress.next;
  for(let i=0;i<stage.questions;i++){
    attemptNo++;
    const r=C.answer(save,"tower-one",{eventId:"answer-event-"+attemptNo,questionId:"Q"+attemptNo,subject:"Geschiedenis",stageId:stage.id,correct:true,verified:true});
    assert.equal(r.ok,true);
    save=r.save;
    if(i===0&&stage.questions>1)assert.equal(C.complete(save,"tower-one").reason,"needs-answers");
  }
  const previousCoins=save.munten;
  const result=C.complete(save,"tower-one");
  assert.equal(result.ok,true);assert.equal(result.stage,stage.id);
  assert.deepEqual(result.visibleParts,P.progress(result.project).visibleParts);
  assert.equal(result.stageStory.id,stage.id);
  assert.ok(result.finished||result.save.munten===previousCoins);
  save=result.save;
}
assert.equal(save.munten,15);
assert.ok(save.constructionUnlocks.includes("wachttoren_toegang"));
assert.ok(save.constructionUnlocks.includes("wachttoren_uitkijkpost"));
assert.ok(save.constructionUnlocks.includes("wachttoren_kaart"));
assert.equal(C.complete(save,"tower-one").reason,"already-complete");
assert.equal(C.answer(save,"tower-one",{eventId:"last-event",questionId:"Q-Last",subject:"Nederlands",stageId:"roof",correct:true,verified:true}).reason,"already-complete");
assert.equal(save.hout,13);assert.equal(save.steen,11);assert.equal(save.planken,11);
assert.equal(C.state(save,"house").progress.current,0,"other project untouched");
assert.deepEqual(save.builds,original.builds);
let poor=C.start({hout:0,steen:0,planken:0,munten:0}, {id:"poor",plotId:"plot-poor",blueprintId:"vakwerkhuis",x:0,z:0}).save;
poor=C.answer(poor,"poor",{eventId:"correct-001",questionId:"A",subject:"Nederlands",stageId:"foundation",correct:true,verified:true}).save;
assert.equal(C.complete(poor,"poor").reason,"needs-materials");
assert.equal(C.state(poor,"poor").correctAnswers,1);
const reloaded=JSON.parse(JSON.stringify(poor));
assert.equal(C.state(reloaded,"poor").correctAnswers,1,"study credits survive JSON save/load");
reloaded.hout=2;reloaded.steen=4;
assert.equal(C.complete(reloaded,"poor").ok,true);
assert.deepEqual(original,{hout:20,steen:20,planken:20,munten:3,builds:[{x:1,y:0,z:2,type:"blok"}],otherSetting:{value:8}});
assert.equal(C.state({},"missing").reason,"project-not-found");
console.log("construction-campaign: alle tests geslaagd");
